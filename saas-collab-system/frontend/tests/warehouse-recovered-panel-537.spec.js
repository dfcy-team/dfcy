import { mount, flushPromises } from '@vue/test-utils';
import { beforeEach, describe, expect, it, vi } from 'vitest';
const request = vi.hoisted(() => vi.fn());
const permissions = vi.hoisted(() => ({ products: true, exceptions: true }));
const authState = vi.hoisted(() => ({ currentUser: { id: 1, tenant_id: 'tenant-a' }, authorizationStale: false, hasPermission: () => true, hasAllDataScopeFor: () => true, instance: null }));
vi.mock('../src/api/request.js', () => ({ default: request }));
vi.mock('../src/stores/auth.js', async () => { const { reactive } = await import('vue'); const instance = reactive(authState); authState.instance = instance; return { useAuthStore: () => instance }; });
vi.mock('../src/components/inventory/RecoveredABCStatus537.js', () => ({ default: { render: () => null } }));
vi.mock('../src/router/menu.js', () => ({
  canAccessPath: () => permissions.products,
  canAccessWarehouseExceptions: () => permissions.exceptions,
}));
import WarehouseInventoryDetails from '../src/views/inventory/WarehouseInventoryDetails.vue';
import RecoveredWarehousePanel537 from '../src/components/inventory/RecoveredWarehousePanel537.js';

describe('warehouse recovered inventory panel', () => {
  beforeEach(() => {
    request.mockReset();
    authState.currentUser = { id: 1, tenant_id: 'tenant-a' };
    authState.authorizationStale = false;
    permissions.products = true;
    permissions.exceptions = true;
    request.mockResolvedValue({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
  });
  it('renders recovered category tree and keeps the exception tab', async () => {
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0, categories: [{ id: 1, name: '服装', parent_id: null }], warehouses: [] } });
    const wrapper = mount(WarehouseInventoryDetails, { global: { stubs: { 'el-tabs': { template: '<div><slot /></div>' }, 'el-tab-pane': { props: ['label'], template: '<section><header>{{ label }}</header><slot /></section>' }, InventoryWorkbench: { template: '<div>异常视图</div>' } } } });
    await flushPromises();
    const countrySelect = wrapper.findComponent({ name: 'ElSelect' });
    countrySelect.vm.$emit('change', '1');
    await flushPromises();
    expect(wrapper.text()).toContain('商品分类');
    expect(wrapper.text()).toContain('服装');
    expect(wrapper.text()).toContain('库存异常清单');
    expect(request).toHaveBeenCalledWith(expect.objectContaining({ url: '/api/internal/commerce/inventory/category-query/' }));
    wrapper.unmount();
  });
  it('preserves single-permission page branches', async () => {
    permissions.exceptions = false;
    const productsOnly = mount(WarehouseInventoryDetails);
    expect(productsOnly.text()).toContain('商品分类');
    productsOnly.unmount();
    permissions.products = false;
    permissions.exceptions = true;
    const exceptionsOnly = mount(WarehouseInventoryDetails);
    expect(exceptionsOnly.find('[aria-label="整款库存"]').exists()).toBe(false);
    expect(exceptionsOnly.text()).not.toContain('商品分类');
    exceptionsOnly.unmount();
  });
  it('loads category data only from the country-scoped real response shape', async () => {
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0, categories: [{ id: 9, parent_id: null, name: '服装' }], warehouses: [] } });
    const wrapper = mount(RecoveredWarehousePanel537, { props: { kind: 'category' } });
    await flushPromises();
    expect(request.mock.calls[0][0].params).toEqual({});
    expect(wrapper.text()).not.toContain('服装');
    const countrySelect = wrapper.findComponent({ name: 'ElSelect' });
    countrySelect.vm.$emit('change', '1');
    await flushPromises();
    expect(request.mock.calls[1][0].params).toMatchObject({ country_id: 1, level: 'spu' });
    expect(wrapper.text()).toContain('服装');
    wrapper.unmount();
  });
  it('uses paged SKU and supported warehouse/store detail levels when expanding an SPU', async () => {
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [{ id: 44, name: '外套', code: 'SPU-44', sku_count: 21, available: 8 }], count: 1, categories: [], warehouses: [] } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [], results: [{ id: 1, name: '外套红色', code: 'SKU-1' }], count: 21, categories: [], warehouses: [] } });
    const wrapper = mount(RecoveredWarehousePanel537, { props: { kind: 'operations' } });
    await flushPromises();
    wrapper.findComponent({ name: 'ElSelect' }).vm.$emit('change', '1');
    await flushPromises();
    const queryButton = wrapper.findAll('button').find(button => button.text().includes('查询'));
    await queryButton.trigger('click');
    await flushPromises();
    const spuButton = wrapper.findAll('button').find(button => button.text().includes('外套'));
    await spuButton.trigger('click');
    await flushPromises();
    expect(request.mock.calls.at(-1)[0].params).toMatchObject({ level: 'sku', spu_id: 44, offset: 0 });
    expect(request.mock.calls.some(([config]) => ['stores', 'warehouses'].includes(config.params?.level))).toBe(false);
    expect(wrapper.text()).toContain('第 1 页 · 共 21 项');
    wrapper.unmount();
  });
  it('requests unmapped stock with the supported level and renders the returned source SKU fields', async () => {
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [], results: [], count: 0, categories: [], warehouses: [] } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [], results: [{ id: 7, source_sku: 'SRC-7', warehouse_id: 3, warehouse__name: '主仓', on_hand_qty: 5, available_qty: null }], count: 1, warehouses: [] } });
    const wrapper = mount(RecoveredWarehousePanel537, { props: { kind: 'operations' } });
    await flushPromises();
    wrapper.findComponent({ name: 'ElSelect' }).vm.$emit('change', '1');
    await flushPromises();
    await wrapper.findAll('button').find(button => button.text().includes('查询')).trigger('click');
    await flushPromises();
    await wrapper.findAll('button').find(button => button.text().includes('未关联商品库存')).trigger('click');
    await flushPromises();
    expect(request.mock.calls.at(-1)[0].params).toMatchObject({ level: 'unmapped', country_id: 1, offset: 0 });
    expect(wrapper.text()).toContain('SRC-7');
    expect(wrapper.text()).toContain('主仓');
    expect(wrapper.text()).toContain('—');
    wrapper.unmount();
  });
  it('keeps two concurrently expanded SPUs usable when their SKU responses arrive out of order', async () => {
    let resolveFirst, resolveSecond;
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [], results: [{ id: 44, name: '外套', code: 'A' }, { id: 55, name: '裤子', code: 'B' }], count: 2, categories: [], warehouses: [] } });
    request.mockImplementationOnce(() => new Promise(resolve => { resolveFirst = resolve; }));
    request.mockImplementationOnce(() => new Promise(resolve => { resolveSecond = resolve; }));
    const wrapper = mount(RecoveredWarehousePanel537, { props: { kind: 'operations' } });
    await flushPromises();
    wrapper.findComponent({ name: 'ElSelect' }).vm.$emit('change', '1');
    await flushPromises();
    await wrapper.findAll('button').find(button => button.text().includes('查询')).trigger('click');
    await flushPromises();
    await wrapper.findAll('button').find(button => button.text().includes('外套')).trigger('click');
    await wrapper.findAll('button').find(button => button.text().includes('裤子')).trigger('click');
    expect(request.mock.calls.slice(-2).map(([config]) => config.params.spu_id)).toEqual([44, 55]);
    resolveSecond({ success: true, data: { results: [{ id: 2, code: 'SKU-PANTS' }], count: 1 } });
    resolveFirst({ success: true, data: { results: [{ id: 1, code: 'SKU-COAT' }], count: 1 } });
    await flushPromises();
    expect(wrapper.text()).toContain('SKU-PANTS');
    expect(wrapper.text()).toContain('SKU-COAT');
    expect(wrapper.text()).not.toContain('正在读取 SKU');
    wrapper.unmount();
  });
  it('clears expanded SKU data synchronously on tenant switch and rejects the old response', async () => {
    let resolveSku;
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [], results: [{ id: 44, name: '外套', code: 'A' }], count: 1, categories: [], warehouses: [] } });
    request.mockImplementationOnce(() => new Promise(resolve => { resolveSku = resolve; }));
    const wrapper = mount(RecoveredWarehousePanel537, { props: { kind: 'operations' } });
    await flushPromises();
    wrapper.findComponent({ name: 'ElSelect' }).vm.$emit('change', '1');
    await flushPromises();
    await wrapper.findAll('button').find(button => button.text().includes('查询')).trigger('click');
    await flushPromises();
    await wrapper.findAll('button').find(button => button.text().includes('外套')).trigger('click');
    authState.instance.currentUser = { id: 2, tenant_id: 'tenant-b' };
    authState.instance.authorizationStale = true;
    await flushPromises();
    expect(wrapper.text()).not.toContain('外套');
    resolveSku({ success: true, data: { results: [{ id: 9, name: '旧租户SKU' }], count: 1 } });
    await flushPromises();
    expect(wrapper.text()).not.toContain('旧租户SKU');
    wrapper.unmount();
  });
  it.each(['success', 'failure'])('ignores the old same-SPU %s after close and reopen', async oldOutcome => {
    let resolveOld, rejectOld, resolveNew;
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [], results: [{ id: 44, name: '外套', code: 'A' }], count: 1, categories: [], warehouses: [] } });
    request.mockImplementationOnce(() => new Promise((resolve, reject) => { resolveOld = resolve; rejectOld = reject; }));
    request.mockImplementationOnce(() => new Promise(resolve => { resolveNew = resolve; }));
    const wrapper = mount(RecoveredWarehousePanel537, { props: { kind: 'operations' } });
    await flushPromises();
    wrapper.findComponent({ name: 'ElSelect' }).vm.$emit('change', '1');
    await flushPromises();
    await wrapper.findAll('button').find(button => button.text().includes('查询')).trigger('click');
    await flushPromises();
    const expand = () => wrapper.findAll('button').find(button => button.text().includes('外套'));
    await expand().trigger('click');
    await expand().trigger('click');
    await expand().trigger('click');
    if (oldOutcome === 'success') resolveOld({ success: true, data: { results: [{ id: 1, code: 'OLD-SKU' }], count: 1 } });
    else rejectOld(new Error('obsolete request failed'));
    resolveNew({ success: true, data: { results: [{ id: 2, code: 'NEW-SKU' }], count: 1 } });
    await flushPromises();
    expect(wrapper.text()).toContain('NEW-SKU');
    expect(wrapper.text()).not.toContain('OLD-SKU');
    expect(wrapper.text()).not.toContain('obsolete request failed');
    wrapper.unmount();
  });
  it('invalidates a pending SKU response when the main result page changes', async () => {
    let resolveSku;
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
    request.mockResolvedValueOnce({ success: true, data: { countries: [], results: [{ id: 44, name: '外套', code: 'A' }], count: 21, categories: [], warehouses: [] } });
    request.mockImplementationOnce(() => new Promise(resolve => { resolveSku = resolve; }));
    request.mockResolvedValueOnce({ success: true, data: { countries: [], results: [{ id: 45, name: '新页面商品', code: 'B' }], count: 21, categories: [], warehouses: [] } });
    const wrapper = mount(RecoveredWarehousePanel537, { props: { kind: 'operations' } });
    await flushPromises();
    wrapper.findComponent({ name: 'ElSelect' }).vm.$emit('change', '1');
    await flushPromises();
    await wrapper.findAll('button').find(button => button.text().includes('查询')).trigger('click');
    await flushPromises();
    await wrapper.findAll('button').find(button => button.text().includes('外套')).trigger('click');
    await wrapper.findAll('button').find(button => button.text().includes('下一页')).trigger('click');
    await flushPromises();
    resolveSku({ success: true, data: { results: [{ id: 9, code: 'STALE-SKU' }], count: 1 } });
    await flushPromises();
    expect(wrapper.text()).toContain('新页面商品');
    expect(wrapper.text()).not.toContain('STALE-SKU');
    wrapper.unmount();
  });
  it('supports category multi-select and applies the stock-only switch to list and SKU GETs', async () => {
    request.mockResolvedValueOnce({ success: true, data: { countries: [{ id: 1, name: '中国', country_code: 'CN' }], results: [], count: 0 } });
    const listResponse = { success: true, data: { countries: [], results: [{ id: 44, name: '外套', code: 'A' }], count: 1, categories: [{ id: 9, name: '服装', parent_id: null }], warehouses: [] } };
    request.mockResolvedValueOnce(listResponse);
    request.mockResolvedValueOnce(listResponse);
    request.mockResolvedValueOnce(listResponse);
    request.mockResolvedValueOnce({ success: true, data: { countries: [], results: [{ id: 1, code: 'SKU-1' }], count: 1, categories: [], warehouses: [] } });
    const wrapper = mount(RecoveredWarehousePanel537, { props: { kind: 'category' } });
    await flushPromises();
    wrapper.findComponent({ name: 'ElSelect' }).vm.$emit('change', '1');
    await flushPromises();
    const categoryToggle = wrapper.get('[aria-label="筛选类目：服装"]');
    await categoryToggle.setValue(true);
    await flushPromises();
    expect(request.mock.calls.at(-1)[0].params).toMatchObject({ category_ids: '9', stocked_only: false });
    await wrapper.get('[aria-label="仅显示有库存"]').setValue(true);
    await flushPromises();
    expect(request.mock.calls.at(-1)[0].params).toMatchObject({ category_ids: '9', stocked_only: true });
    await wrapper.findAll('button').find(button => button.text().includes('外套')).trigger('click');
    await flushPromises();
    expect(request.mock.calls.at(-1)[0].params).toMatchObject({ level: 'sku', spu_id: 44, stocked_only: true });
    wrapper.unmount();
  });
});

